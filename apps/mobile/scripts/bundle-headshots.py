#!/usr/bin/env python3
"""Bundle every portrait into the app (offline-safe). Run after export-website-content.ts:
   python3 scripts/bundle-headshots.py
Downloads each person's approved image to assets/people/<slug>.jpg (400px), keeps any headshot already
placed there by hand, rewrites image to "local:<slug>" and generates lib/headshots.generated.ts."""
import json, re, subprocess, urllib.request, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data_path = root / "lib/summit-content.generated.json"
people_dir = root / "assets/people"
data = json.loads(data_path.read_text())

def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", re.sub(r"\([^)]*\)", "", name.lower())).strip("-")

def fetch(url, target):
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 Safari/605.1.15"})
    raw = target.with_suffix(".download")
    raw.write_bytes(urllib.request.urlopen(request, timeout=60).read())
    subprocess.run(["sips", "-s", "format", "jpeg", "-Z", "400", str(raw), "--out", str(target)], check=True, capture_output=True)
    raw.unlink()

entries = data["people"] + ([data["awards"]["host"]] if data["awards"].get("host") else [])
missing = []
for person in entries:
    key = slug(person["name"])
    target = people_dir / f"{key}.jpg"
    source = person.get("imageSource") or person.get("image")
    if source and source.startswith("local:"):
        source = person.get("imageSource")
    if not target.exists() and source and source.startswith("http"):
        fetch(source, target)
    if target.exists():
        person["imageSource"] = source if source and source.startswith("http") else person.get("imageSource")
        person["image"] = f"local:{key}"
    else:
        person["image"] = None
        missing.append(person["name"])

data_path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
keys = sorted({p["image"][6:] for p in entries if p.get("image")})
lines = ["// Generated by scripts/bundle-headshots.py. Bundled portraits keyed by slug.", "export const headshots: Record<string, number> = {"]
lines += [f'  "{k}": require("../assets/people/{k}.jpg"),' for k in keys]
lines += ["};", ""]
(root / "lib/headshots.generated.ts").write_text("\n".join(lines))
print(f"{len(keys)} bundled; missing: {', '.join(missing) or 'none'}")
